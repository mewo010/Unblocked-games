// In-site stream builder for movies & TV series
export function getMovieStreamUrl(
  movie: MovieItem,
  serverIndex: number = 0,
  season: number = 1,
  episode: number = 1
): string {
  const isTv = movie.type === 'tv';
  const tmdb = movie.tmdbId;
  const imdb = movie.imdbId || '';

  const servers = isTv
    ? [
        `https://multiembed.mov/?video_id=${tmdb}&tmdb=1&s=${season}&e=${episode}`,
        `https://vidsrc.to/embed/tv/${tmdb}/${season}/${episode}`,
        `https://vidsrc.xyz/embed/tv/${tmdb}/${season}/${episode}`,
        `https://autoembed.co/tv/tmdb/${tmdb}-${season}-${episode}`,
        `https://2embed.cc/embedtv/${tmdb}&s=${season}&e=${episode}`,
        `https://embed.su/embed/tv/${tmdb}/${season}/${episode}`,
      ]
    : [
        `https://multiembed.mov/?video_id=${tmdb}&tmdb=1`,
        `https://vidsrc.to/embed/movie/${tmdb}`,
        `https://embed.su/embed/movie/${tmdb}`,
        `https://vidsrc.xyz/embed/movie/${tmdb}`,
        `https://autoembed.co/movie/tmdb/${tmdb}`,
        `https://2embed.cc/embed/${tmdb}`,
        imdb ? `https://vidsrc.me/embed/movie?imdb=${imdb}` : `https://vidsrc.to/embed/movie/${tmdb}`,
      ];

  return servers[serverIndex % servers.length];
}
